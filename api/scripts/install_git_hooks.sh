#!/usr/bin/env bash
# Install the repository's git hooks. Idempotent; safe to re-run.
#
# Why a hook rather than a self-hosted runner
# ───────────────────────────────────────────
# GitHub Actions has not executed since ~2026-07-21 (billing), so every gate in
# this repository is local-only and runs when someone remembers. The obvious fix
# is a self-hosted runner, and it is the wrong fix *on this machine*: the
# repository is public, `ci.yml` and `frontend.yml` trigger on `pull_request`, and
# this host holds the production SSH key and the live `.env`. A self-hosted runner
# would let anyone who opens a pull request run code with access to both.
#
# This is the part of CI that can be had with no exposure: the fast, static gates,
# run before every push. It is not a substitute for CI — it proves nothing about
# any machine but this one, and it can be skipped with `--no-verify`. What it does
# is convert "someone remembers" into "you have to opt out".
#
#     ./scripts/install_git_hooks.sh
#     git push                    # gates run
#     git push --no-verify        # deliberately skipped
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# Install into this repository, never into `core.hooksPath`. `--git-path hooks`
# follows core.hooksPath, so on a machine with a global hooks path this script
# overwrote the machine-wide pre-push hook (a ggshield wrapper) for every
# repository on 2026-11-11. When core.hooksPath is set, git runs hooks only from
# there, so this hook then runs only if the hook there chains
# `$(git rev-parse --git-dir)/hooks/pre-push`, as that wrapper does.
HOOKS_PATH="$(git -C "$ROOT" config --get core.hooksPath || true)"
if [[ -n "$HOOKS_PATH" ]]; then
    HOOK_DIR="$(git -C "$ROOT" rev-parse --absolute-git-dir)/hooks"
else
    HOOK_DIR="$(git -C "$ROOT" rev-parse --path-format=absolute --git-path hooks)"
fi
mkdir -p "$HOOK_DIR"
# Never replace a hook this script did not write.
if [[ -e "$HOOK_DIR/pre-push" ]] && ! grep -q 'Generated by scripts/install_git_hooks.sh' "$HOOK_DIR/pre-push"; then
    echo "refusing to overwrite $HOOK_DIR/pre-push: this script did not write it" >&2
    exit 1
fi

cat > "$HOOK_DIR/pre-push" <<'HOOK'
#!/usr/bin/env bash
# Generated by scripts/install_git_hooks.sh — re-run it to update.
#
# The fast static gates only. Anything needing a database, a network round trip or
# more than a few seconds belongs in the full suite, because a slow hook is a hook
# people disable — and a disabled gate is worse than an absent one, since it still
# reads as coverage.
set -uo pipefail

ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT" || exit 0
[[ -x .venv/bin/python ]] || { echo "pre-push: no .venv, skipping gates"; exit 0; }

# Only the gates that exist — this hook outlives any particular file name.
GATES=()
for t in tests/test_migration_ledger.py \
         tests/test_no_runtime_ddl.py \
         tests/test_startup_env_is_wired.py \
         tests/test_source_tree_is_shared.py \
         tests/test_companion_schema_discipline.py \
         tests/test_sql_injection_guard.py \
         tests/test_internal_documents_are_not_tracked.py; do
    [[ -f "$t" ]] && GATES+=("$t")
done

echo "pre-push: ruff + ${#GATES[@]} static gates"

if ! .venv/bin/ruff check . --quiet; then
    echo "pre-push: ruff failed — fix or 'git push --no-verify'" >&2
    exit 1
fi

set -a; [[ -f .env.test ]] && . ./.env.test >/dev/null 2>&1; set +a
if ! .venv/bin/python -m pytest "${GATES[@]}" -q -p no:sugar -p no:randomly >/tmp/xcelsior-prepush.log 2>&1; then
    echo "pre-push: static gates failed — see /tmp/xcelsior-prepush.log" >&2
    tail -20 /tmp/xcelsior-prepush.log >&2
    exit 1
fi

echo "pre-push: ok (full suite still yours to run: ./run-tests.sh)"
HOOK

chmod +x "$HOOK_DIR/pre-push"
echo "installed $HOOK_DIR/pre-push"
if [[ -n "$HOOKS_PATH" ]]; then
    echo "note: core.hooksPath is $HOOKS_PATH, so git runs hooks from there; this"
    echo "hook runs only if $HOOKS_PATH/pre-push chains the repository's own hook."
fi
echo
echo "This is not CI. It runs the fast gates on this machine only, and"
echo "'git push --no-verify' skips it. The full suite is still ./run-tests.sh,"
echo "and remote verification still needs Actions billing or a runner on a host"
echo "that does NOT hold the production key - see A1 of the internal plan"
echo "~/xcelsior-internal-docs/api/docs/review/workaround-elimination-plan.md."
