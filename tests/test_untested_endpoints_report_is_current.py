"""The coverage-gap worklist must reflect the routes that exist.

`UNTESTED_ENDPOINTS.md` is generated by
`scripts/regenerate_untested_endpoints.py` and declares itself so in its own
header — then nothing checked it. Measured 2026-09-19, the committed file said:

    **0 of 373 routes (0%)** and **0 of 51 CLI commands** (0%) have no test signal.

while a fresh run said **32 of 529 routes (6%)**. A worklist of coverage gaps,
reporting zero gaps, with thirty-two of them — and 156 routes added since it was
last written. Read at face value it says the work is done.

The report stamps `date.today()`, so it is deliberately NOT byte-comparable;
this compares everything else. A date-only difference is expected and must not
fail, or the gate cries wolf daily and gets deleted.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATOR = ROOT / "scripts" / "regenerate_untested_endpoints.py"
REPORT = ROOT / "UNTESTED_ENDPOINTS.md"

#: The one line allowed to differ: it carries the generation date.
STAMP_PREFIX = "_Regenerated "


def _substance(text: str) -> list[str]:
    return [ln for ln in text.splitlines() if not ln.startswith(STAMP_PREFIX)]


def _regenerate() -> str:
    """Run the generator against a copy of the tree, never the real report.

    The script writes to `PROJECT / "UNTESTED_ENDPOINTS.md"` with no --output,
    so it is run with the repo's report temporarily moved aside and restored in
    a finally. Editing the checked-in file as a side effect of *checking* it
    would be its own kind of drift.
    """
    with tempfile.TemporaryDirectory() as tmp:
        backup = Path(tmp) / "report.md"
        shutil.copy2(REPORT, backup)
        try:
            result = subprocess.run(
                [sys.executable, str(GENERATOR)],
                cwd=ROOT,
                capture_output=True,
                text=True,
                timeout=300,
            )
            if result.returncode != 0:
                # A generator that cannot run is a FAILURE of this gate, never a
                # skip — see tests/test_generated_artifacts_are_current.py, where
                # a skip here hid real drift behind a green suite.
                raise AssertionError(
                    f"the generator could not run, so nothing is checking "
                    f"{REPORT.name}: rc={result.returncode} {result.stderr[-400:]}"
                )
            return REPORT.read_text(encoding="utf-8")
        finally:
            shutil.copy2(backup, REPORT)


def test_the_generator_and_report_both_exist() -> None:
    assert GENERATOR.exists(), f"{GENERATOR} is gone; the report has no source"
    assert REPORT.exists(), f"{REPORT} is missing; regenerate it"


def test_the_report_declares_itself_generated() -> None:
    assert STAMP_PREFIX in REPORT.read_text(encoding="utf-8")[:1000], (
        "the report no longer names its generator; a file nobody knows is "
        "generated gets hand-edited"
    )


def test_the_report_matches_a_fresh_generation() -> None:
    fresh = _regenerate()
    committed = REPORT.read_text(encoding="utf-8")
    if _substance(committed) == _substance(fresh):
        return

    import difflib

    delta = list(
        difflib.unified_diff(
            _substance(committed), _substance(fresh),
            fromfile="committed", tofile="fresh", lineterm="", n=0,
        )
    )
    raise AssertionError(
        "UNTESTED_ENDPOINTS.md does not match a fresh generation — the coverage "
        "worklist is describing a codebase that no longer exists. Run "
        "`python scripts/regenerate_untested_endpoints.py` and commit it.\n"
        + "\n".join(delta[:20])
    )


def test_a_date_only_change_does_not_fail_the_gate() -> None:
    """The stamp changes daily; only substance may fail this."""
    body = REPORT.read_text(encoding="utf-8")
    assert _substance(body) == _substance(
        body.replace("_Regenerated 2026-", "_Regenerated 1999-", 1)
    ), "the date stamp is not being excluded, so this gate would fail every day"
